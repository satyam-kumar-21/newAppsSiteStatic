const categoryList = document.querySelector("#apps-category-list");
const pageTitle = document.querySelector("#apps-page-title");
const pageDescription = document.querySelector("#apps-page-description");
const metaDescription = document.querySelector('meta[name="description"]');

if (categoryList && pageTitle && pageDescription) {
  const parameters = new URLSearchParams(window.location.search);
  const requestedSlug = parameters.get("category");
  const searchQuery = parameters.get("q")?.trim() || "";
  if (searchQuery || requestedSlug) {
    const robotsMeta = document.querySelector('meta[name="robots"]');
    if (robotsMeta) {
      robotsMeta.content = "noindex, follow";
    }
  }
  const normalizedQuery = searchQuery.toLocaleLowerCase();
  const searchResults = searchQuery
    ? (window.catalogSearchItems || []).filter((app) =>
        [app.title, app.categoryName, app.developer, app.type]
          .filter(Boolean)
          .some((value) => value.toLocaleLowerCase().includes(normalizedQuery)),
      )
    : [];
  const selectedCategory = appCategories.find((category) => category.slug === requestedSlug);
  const categoriesToShow = searchQuery
    ? [{ name: `Search results for ${searchQuery}`, apps: searchResults }]
    : selectedCategory ? [selectedCategory] : appCategories;
  const appPageUrl = new URL("apps.html", window.location.href);

  function getAppPageUrl(app) {
    return `${app.appurl.replace(/\/+$/, "")}.html`;
  }

  function createAdSlot(slotId) {
    const slot = document.createElement("aside");
    slot.className = "ad-slot";
    slot.id = `ad-slot-${slotId}`;
    slot.setAttribute("aria-label", "Advertisement");

    const content = document.createElement("div");
    const label = document.createElement("span");
    label.className = "ad-slot-label";
    label.textContent = "Advertisement";

    const copy = document.createElement("span");
    copy.className = "ad-slot-copy";
    copy.textContent = "Ad placement reserved";
    content.append(label, copy);
    slot.append(content);
    return slot;
  }

  function createAppCard(app, category) {
    const appCategoryName = app.categoryName || category.name;
    const ratingValue = Number(app.ratings);
    const hasRating = app.ratings !== undefined && app.ratings !== null && String(app.ratings).trim() !== "" && Number.isFinite(ratingValue);
    const card = document.createElement("a");
    card.className = "app-card";
    card.href = getAppPageUrl(app);
    card.setAttribute(
      "aria-label",
      hasRating ? `${app.title}, ${appCategoryName}, rated ${ratingValue.toFixed(1)} out of 5` : `${app.title}, ${appCategoryName}`,
    );

    const icon = document.createElement("span");
    icon.className = "app-card-icon";
    icon.setAttribute("aria-hidden", "true");
    const initials = document.createElement("span");
    initials.textContent = app.title
      .split(/\s+/)
      .slice(0, 2)
      .map((word) => word.charAt(0))
      .join("")
      .toUpperCase();
    icon.append(initials);

    if (app.icon) {
      const image = document.createElement("img");
      image.src = app.icon;
      image.alt = "";
      image.loading = "lazy";
      image.decoding = "async";
      image.addEventListener("error", () => image.remove());
      icon.append(image);
    }

    const copy = document.createElement("span");
    copy.className = "app-card-copy";

    const title = document.createElement("span");
    title.className = "app-card-title";
    title.textContent = app.title;

    const categoryLabel = document.createElement("span");
    categoryLabel.className = "app-card-category";
    categoryLabel.textContent = appCategoryName;

    copy.append(title, categoryLabel);
    if (hasRating) {
      const rating = document.createElement("span");
      rating.className = "app-card-rating";
      rating.setAttribute("aria-label", `Rated ${ratingValue.toFixed(1)} out of 5`);

      const star = document.createElement("span");
      star.className = "app-card-star";
      star.setAttribute("aria-hidden", "true");
      star.textContent = "★";

      const ratingText = document.createElement("span");
      ratingText.textContent = ratingValue.toFixed(1);

      rating.append(star, ratingText);
      copy.append(rating);
    }
    card.append(icon, copy);
    return card;
  }

  function createCategorySection(category, showAll) {
    const section = document.createElement("section");
    section.className = "apps-category";
    section.id = `category-${category.slug}`;
    section.setAttribute("aria-labelledby", `heading-${category.slug}`);

    const heading = document.createElement("div");
    heading.className = "apps-category-heading";

    const title = document.createElement("h2");
    title.id = `heading-${category.slug}`;
    title.textContent = category.name;

    heading.append(title);
    if (!showAll) {
      const viewAll = document.createElement("a");
      viewAll.className = "apps-view-all";
      viewAll.href = `apps.html?category=${encodeURIComponent(category.slug)}`;
      viewAll.setAttribute("aria-label", `View all ${category.name} apps`);
      viewAll.title = `View all ${category.name} apps`;

      const arrow = document.createElementNS("http://www.w3.org/2000/svg", "svg");
      arrow.setAttribute("viewBox", "0 0 24 24");
      arrow.setAttribute("aria-hidden", "true");

      const arrowPath = document.createElementNS("http://www.w3.org/2000/svg", "path");
      arrowPath.setAttribute("d", "M5 12h13m-6-6 6 6-6 6");
      arrow.append(arrowPath);
      viewAll.append(arrow);
      heading.append(viewAll);
    }

    const grid = document.createElement("div");
    grid.className = "apps-grid";
    grid.setAttribute("role", "list");

    const appsToShow = showAll ? category.apps : category.apps.slice(0, 9);
    appsToShow.forEach((app) => {
      const card = createAppCard(app, category);
      card.setAttribute("role", "listitem");
      grid.append(card);
    });

    section.append(heading, grid);
    return section;
  }

  function setStructuredData(categories) {
    const existing = document.querySelector("#apps-structured-data");
    existing?.remove();

    const structuredData = {
      "@context": "https://schema.org",
      "@type": "ItemList",
      "itemListElement": categories.flatMap((category) =>
        category.apps.map((app, index) => ({
          "@type": "ListItem",
          "position": index + 1,
          "name": app.title,
          "url": new URL(getAppPageUrl(app), window.location.origin).href,
          "category": category.name,
        })),
      ),
    };

    const script = document.createElement("script");
    script.id = "apps-structured-data";
    script.type = "application/ld+json";
    script.textContent = JSON.stringify(structuredData).replace(/</g, "\\u003c");
    document.head.append(script);
  }

  if (searchQuery) {
    categoryList.replaceChildren();
    const resultCount = searchResults.length;
    pageTitle.textContent = `Search results for "${searchQuery}"`;
    pageDescription.textContent = resultCount
      ? `Found ${resultCount} matching ${resultCount === 1 ? "app or game" : "apps and games"}.`
      : `No apps or games matched "${searchQuery}". Try another search.`;
    document.title = `Search results for ${searchQuery} | BRANDNAME`;
    if (metaDescription) {
      metaDescription.content = pageDescription.textContent;
    }

    const section = document.createElement("section");
    section.className = "apps-category";
    section.id = "search-results";
    section.setAttribute("aria-labelledby", "search-results-heading");

    const heading = document.createElement("div");
    heading.className = "apps-category-heading";
    const title = document.createElement("h2");
    title.id = "search-results-heading";
    title.textContent = resultCount ? `${resultCount} results` : "No results";
    heading.append(title);
    section.append(heading);

    if (resultCount) {
      const grid = document.createElement("div");
      grid.className = "apps-grid";
      grid.setAttribute("role", "list");
      searchResults.forEach((app) => {
        const card = createAppCard(app, { name: app.categoryName });
        card.setAttribute("role", "listitem");
        grid.append(card);
      });
      section.append(grid);
    } else {
      const emptyMessage = document.createElement("p");
      emptyMessage.className = "apps-message";
      emptyMessage.textContent = "Check the spelling or try a different app, game, or category name.";
      section.append(emptyMessage);
    }
    categoryList.append(section, createAdSlot("search-results"));
  } else if (requestedSlug && !selectedCategory) {
    categoryList.replaceChildren();
    pageTitle.textContent = "App category not found";
    pageDescription.textContent = "The requested app category is unavailable. Browse all app categories below.";
    document.title = "App Category Not Found | BRANDNAME";
    if (metaDescription) {
      metaDescription.content = pageDescription.textContent;
    }
    appCategories.forEach((category) => {
      categoryList.append(createCategorySection(category, false), createAdSlot(`apps-${category.slug}`));
    });
  } else if (selectedCategory) {
    categoryList.replaceChildren();
    pageTitle.textContent = `All ${selectedCategory.name} apps`;
    pageDescription.textContent = `Browse every ${selectedCategory.name.toLowerCase()} app in our catalog, with ratings and links to each app.`;
    document.title = `All ${selectedCategory.name} Apps | BRANDNAME`;
    if (metaDescription) {
      metaDescription.content = pageDescription.textContent;
    }

    const backLink = document.createElement("a");
    backLink.className = "apps-back-link";
    backLink.href = appPageUrl.href;
    backLink.textContent = "Browse all categories";
    categoryList.append(
      backLink,
      createCategorySection(selectedCategory, true),
      createAdSlot(`apps-${selectedCategory.slug}`),
    );
  } else {
    if (categoryList.childElementCount === 0) {
      appCategories.forEach((category) => {
        categoryList.append(createCategorySection(category, false), createAdSlot(`apps-${category.slug}`));
      });
    }
    if (metaDescription) {
      metaDescription.content = pageDescription.textContent.trim();
    }
  }

  setStructuredData(categoriesToShow);
}
