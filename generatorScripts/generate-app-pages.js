function updatePolicyAdSlots() {
  const policyPages = ["privacy", "terms", "disclaimer"];
  const managedSlotPattern = /<aside class="ad-slot"[^>]*data-generated-ad-slot="policy">[\s\S]*?<\/aside>/g;
  const policySectionPattern = /<section class="(?:about-hero legal-hero|legal-section)"[^>]*>[\s\S]*?<\/section>/g;

  for (const pageName of policyPages) {
    const filePath = path.join(ROOT, pageName, "index.html");
    const original = fs.readFileSync(filePath, "utf8");
    const cleanPage = original.replace(managedSlotPattern, "");
    let sectionIndex = 0;
    let updated = cleanPage.replace(policySectionPattern, (section) => {
      sectionIndex += 1;
      return `${section}\n${renderAdSlot(`policy-${pageName}-${sectionIndex}`, ' data-generated-ad-slot="policy"')}`;
    });
    if (sectionIndex === 0) {
      throw new Error(`Could not find policy content sections in ${pageName}/index.html.`);
    }
    if (!/<link rel="stylesheet" href="\/styles\/apps\.css"\s*\/>/.test(updated)) {
      updated = updated.replace(
        /(<link rel="stylesheet" href="\/styles\/responsive\.css"\s*\/>)/,
        '$1\n    <link rel="stylesheet" href="/styles/apps.css" />',
      );
    }
    fs.writeFileSync(filePath, updated, "utf8");
  }
}

