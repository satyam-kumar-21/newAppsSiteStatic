function writePages(categories, shell) {
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  const allApps = categories.flatMap((category) => category.apps);
  const expectedFiles = new Set();
  let written = 0;

  for (const category of categories) {
    for (const app of category.apps) {
      const outputPath = path.join(ROOT, app.pagePath.replace(/^\/+/, ""), "index.html");
      expectedFiles.add(path.resolve(outputPath).toLowerCase());
      if (fs.existsSync(outputPath) && !fs.readFileSync(outputPath, "utf8").includes(GENERATED_MARKER)) {
        throw new Error(`Refusing to overwrite an unmanaged file: ${path.relative(ROOT, outputPath)}`);
      }
      const html = `${GENERATED_MARKER}\n${renderPage(app, category, allApps, shell)}\n`;
      fs.mkdirSync(path.dirname(outputPath), { recursive: true });
      fs.writeFileSync(outputPath, html, "utf8");
      written += 1;
    }
  }

  const cleanStalePages = (directory, marker = GENERATED_MARKER) => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const fullPath = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        cleanStalePages(fullPath, marker);
        continue;
      }
      if (!entry.isFile() || !entry.name.toLowerCase().endsWith(".html")) {
        continue;
      }
      const normalizedPath = path.resolve(fullPath).toLowerCase();
      if (!expectedFiles.has(normalizedPath) && fs.readFileSync(fullPath, "utf8").includes(marker)) {
        fs.unlinkSync(fullPath);
      }
    }
  };
  cleanStalePages(OUTPUT_DIR);
  cleanGeneratedPages(path.join(ROOT, "apps"), [
    "<!-- Generated by generate-app-pages.js. Do not edit this file directly. -->",
    "<!-- Generated by generate-app-pages.js for games. Do not edit this file directly. -->",
  ]);
  cleanGeneratedPages(path.join(ROOT, "games"), [
    "<!-- Generated by generate-app-pages.js. Do not edit this file directly. -->",
    "<!-- Generated by generate-app-pages.js for games. Do not edit this file directly. -->",
  ]);
  removeEmptyGeneratedDirectories(path.join(ROOT, "apps"));
  removeEmptyGeneratedDirectories(path.join(ROOT, "games"));
  removeEmptyGeneratedDirectories(path.join(ROOT, "game"));
  writeSitemap(allApps, categories);
  return written;
}

function cleanGeneratedPages(directory, markers) {
  if (!fs.existsSync(directory)) {
    return;
  }
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      cleanGeneratedPages(fullPath, markers);
      continue;
    }
    if (!entry.isFile() || !entry.name.toLowerCase().endsWith(".html")) {
      continue;
    }
    const contents = fs.readFileSync(fullPath, "utf8");
    if (markers.some((marker) => contents.includes(marker))) {
      fs.unlinkSync(fullPath);
    }
  }
}

function removeEmptyGeneratedDirectories(directory) {
  if (!fs.existsSync(directory) || !fs.statSync(directory).isDirectory()) {
    return;
  }
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      removeEmptyGeneratedDirectories(path.join(directory, entry.name));
    }
  }
  if (directory !== ROOT && fs.readdirSync(directory).length === 0) {
    fs.rmdirSync(directory);
  }
}

function writeSitemap(apps, categories) {
  if (fs.existsSync(SITEMAP_FILE) && !fs.readFileSync(SITEMAP_FILE, "utf8").includes(GENERATED_SITEMAP_MARKER)) {
    throw new Error("Refusing to overwrite the existing unmanaged app-sitemap.xml file.");
  }
  const urls = [
    ...categories.map((category) => `  <url><loc>${escapeHtml(absoluteUrl(`/${ITEMS_LABEL}/${category.slug}`))}</loc></url>`),
    ...apps.map((app) => `  <url><loc>${escapeHtml(absoluteUrl(app.pagePath))}</loc></url>`),
  ].join("\n");
  const sitemap = `<?xml version="1.0" encoding="UTF-8"?>\n${GENERATED_SITEMAP_MARKER}\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`;
  fs.writeFileSync(SITEMAP_FILE, sitemap, "utf8");
}

function writeRootSitemaps() {
  const generatedMarker = "<!-- Generated by generate-app-pages.js. -->";
  const staticPaths = [
    "/",
    "/apps",
    "/games",
    "/about",
    "/privacy",
    "/terms",
    "/disclaimer",
  ];
  const staticUrls = staticPaths.map((url) => `  <url><loc>${escapeHtml(absoluteUrl(url))}</loc></url>`).join("\n");
  const staticSitemap = `<?xml version="1.0" encoding="UTF-8"?>\n${generatedMarker}\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${staticUrls}\n</urlset>\n`;
  const sitemapIndex = `<?xml version="1.0" encoding="UTF-8"?>\n${generatedMarker}\n<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n  <sitemap><loc>${escapeHtml(absoluteUrl("/site-sitemap.xml"))}</loc></sitemap>\n  <sitemap><loc>${escapeHtml(absoluteUrl("/apps/app-sitemap.xml"))}</loc></sitemap>\n  <sitemap><loc>${escapeHtml(absoluteUrl("/games/game-sitemap.xml"))}</loc></sitemap>\n</sitemapindex>\n`;
  const robots = `${GENERATED_ROBOTS_MARKER}\nUser-agent: *\nAllow: /\n\nSitemap: ${absoluteUrl("/sitemap.xml")}\n`;
  for (const [filePath, content, description] of [
    [SITE_SITEMAP_FILE, staticSitemap, "site-sitemap.xml"],
    [SITEMAP_INDEX_FILE, sitemapIndex, "sitemap.xml"],
  ]) {
    if (fs.existsSync(filePath) && !fs.readFileSync(filePath, "utf8").includes(generatedMarker)) {
      throw new Error(`Refusing to overwrite an unmanaged ${description} file.`);
    }
    fs.writeFileSync(filePath, content, "utf8");
  }
  if (fs.existsSync(ROBOTS_FILE) && !fs.readFileSync(ROBOTS_FILE, "utf8").includes(GENERATED_ROBOTS_MARKER)) {
    throw new Error("Refusing to overwrite an unmanaged robots.txt file.");
  }
  fs.writeFileSync(ROBOTS_FILE, robots, "utf8");
}

function applyConfiguredBranding() {
  const updateDirectory = (directory) => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const filePath = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        if (entry.name !== ".git" && entry.name !== "assets" && entry.name !== "data" && entry.name !== "generatorScripts") {
          updateDirectory(filePath);
        }
        continue;
      }
      if (!entry.isFile() || ![".html", ".js"].includes(path.extname(entry.name).toLowerCase())) {
        continue;
      }
      const original = fs.readFileSync(filePath, "utf8");
      const updated = replaceBranding(original, "BRANDNAME", BRAND_NAME, filePath.endsWith(".html"));
      if (updated !== original) {
        fs.writeFileSync(filePath, updated, "utf8");
      }
    }
  };
  updateDirectory(ROOT);
}

function updateInternalPageLinks() {
  const categoryTypes = new Map();
  for (const type of ["apps", "games"]) {
    const data = JSON.parse(fs.readFileSync(path.join(ROOT, "data", `${type}.json`), "utf8"));
    const subcategories = data?.[type]?.subcategories || {};
    for (const [key, category] of Object.entries(subcategories)) {
      categoryTypes.set(category.slug || slugify(key), type);
    }
  }
  const updateDirectory = (directory) => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const filePath = path.join(directory, entry.name);
      if (entry.isDirectory()) {
        updateDirectory(filePath);
        continue;
      }
      if (!entry.isFile() || !entry.name.toLowerCase().endsWith(".html")) {
        continue;
      }
      let html = fs.readFileSync(filePath, "utf8");
      const fallbackCatalog = filePath.startsWith(`${path.join(ROOT, "games")}${path.sep}`) ? "games" : "apps";
      html = html.replace(
        /<a\b([^>]*href="\/app\/index\/index\.html(?:[?#][^"]*)?"[^>]*)>([\s\S]*?)<\/a>/gi,
        (anchor, attributes, content) => {
          const href = attributes.match(/href="([^"]+)"/i)?.[1] || "";
          const categorySlug = href.match(/(?:category-|[?&]category=)([^&#]+)/i)?.[1];
          const categoryType = categorySlug ? categoryTypes.get(decodeURIComponent(categorySlug)) : undefined;
          const text = content.replace(/<!--[\s\S]*?-->|<[^>]*>/g, " ").toLowerCase();
          const catalogType = categoryType || (text.includes("game") ? "games" : text.includes("app") ? "apps" : fallbackCatalog);
          return anchor.replace(href, `/${catalogType}/index.html${href.includes("?") ? `?${href.split("?")[1]}` : href.includes("#") ? `#${href.split("#")[1]}` : ""}`);
        },
      );
      const normalizeLink = (value) => {
        if (/^(?:[a-z][a-z\d+.-]*:|\/\/|#|\?)/i.test(value)) {
          return value;
        }
        let localPath = value.startsWith("/") ? value : `/${value}`;
        const brokenCatalogRoute = localPath.match(/^\/app\/index\/index\.html([?#].*)?$/);
        if (brokenCatalogRoute) {
          const categorySlug = brokenCatalogRoute[1]?.match(/[?&]category=([^&#]+)/i)?.[1]
            || brokenCatalogRoute[1]?.match(/category-([^&#]+)/i)?.[1];
          const categoryType = categorySlug ? categoryTypes.get(decodeURIComponent(categorySlug)) : undefined;
          const catalogType = categoryType || (fallbackCatalog === "games" ? "games" : "apps");
          localPath = `/${catalogType}${brokenCatalogRoute[1] || ""}`;
        }
        localPath = localPath.replace(
          /^\/(?:apps|games|game)\/([^/?#]+)(?:\.html|\/index\.html|\/)(?=([?#]|$))/,
          (match, slug) => categoryTypes.has(decodeURIComponent(slug)) ? match : `/app/${slug}`,
        );
        return publicPath(localPath);
      };
      html = html
        .replace(/(href|action)="([^"]+)"/g, (_match, attribute, value) => `${attribute}="${normalizeLink(value)}"`)
        .replace(/(<form\b[^>]*\baction=")\/apps(")/gi, "$1/apps/$2")
        .replace(/(href|src)="\/?(style|common|responsive|apps|about|catalog)\.css"/g, '$1="/styles/$2.css"')
        .replace(/src="\/?(script|search-index|apps|games)\.js"/g, 'src="/scripts/$1.js"');
      html = ensureSearchIndexScript(html);
      fs.writeFileSync(filePath, html, "utf8");
    }
  };
  updateDirectory(ROOT);
}

