function safeLocalPath(value, fieldName) {
  if (typeof value !== "string" || !value.startsWith("/") || value.startsWith("//") || value.includes("\\") || value.split("/").includes("..")) {
    throw new Error(`Invalid ${fieldName} path: ${value}`);
  }
  return value;
}

function publicPath(localPath) {
  if (typeof localPath !== "string" || !localPath) {
    throw new Error(`Invalid public URL path: ${localPath}`);
  }
  if (/^(?:[a-z][a-z\d+.-]*:|\/\/|#|\?)/i.test(localPath)) {
    return localPath;
  }
  const safePath = safeLocalPath(localPath.startsWith("/") ? localPath : `/${localPath}`, "public URL");
  return safePath
    .replace(/^\/index\.html(?=$|[?#])/, "/")
    .replace(/\/index\.html(?=$|[?#])/, "")
    .replace(/\.html(?=$|[?#])/, "");
}

function slugify(value) {
  return String(value ?? "")
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function getDetailPath(item, routePrefix, itemLabel) {
  const title = typeof item.title === "string" ? item.title.trim() : "";
  let appUrl = typeof item.appurl === "string" ? item.appurl.trim() : "";
  if (!appUrl) {
    appUrl = slugify(title);
    if (!appUrl) {
      throw new Error(`A ${itemLabel} needs a title or appurl to generate its detail page.`);
    }
  }

  if (!appUrl.startsWith("/")) {
    if (!/^[a-z0-9._~-]+$/i.test(appUrl)) {
      throw new Error(`Invalid ${itemLabel} URL: ${item.appurl}`);
    }
    appUrl = `/${appUrl}`;
  }
  appUrl = safeLocalPath(appUrl, `${title || itemLabel} appurl`).replace(/\/+$/, "");

  for (const oldPrefix of ["/apps/", "/games/", "/game/"]) {
    if (appUrl.startsWith(oldPrefix)) {
      appUrl = `${routePrefix}${appUrl.slice(oldPrefix.length)}`;
      break;
    }
  }
  if (appUrl.endsWith("/index.html")) {
    appUrl = appUrl.slice(0, -"/index.html".length);
  }

  if (!appUrl.startsWith(routePrefix)) {
    const routeSlug = appUrl.slice(1);
    if (!routeSlug || routeSlug.includes("/")) {
      throw new Error(`Expected a ${itemLabel} URL under ${routePrefix}, or a single route slug: ${item.appurl}`);
    }
    appUrl = `${routePrefix}${routeSlug}`;
  }
  if (appUrl.length <= routePrefix.length) {
    throw new Error(`Expected a ${itemLabel} URL under ${routePrefix}: ${item.appurl}`);
  }
  return appUrl;
}

function getPagePath(app) {
  return getDetailPath(app, ROUTE_PREFIX, ITEM_LABEL);
}

function getTitleFromPath(pagePath, routePrefix) {
  const slug = pagePath.slice(routePrefix.length).replace(/\/+$/, "").split("/").pop();
  return slug.split(/[._-]+/).filter(Boolean).map((part) => part[0].toUpperCase() + part.slice(1)).join(" ");
}

function absoluteUrl(localPath) {
  return new URL(publicPath(localPath), `${SITE_URL}/`).href;
}

function safeExternalUrl(value) {
  if (typeof value !== "string" || !value.trim()) {
    return "";
  }
  const url = new URL(value);
  if (url.protocol !== "https:" && url.protocol !== "http:") {
    throw new Error(`Unsupported store URL protocol: ${value}`);
  }
  return url.href;
}

function loadCategories() {
  if (!fs.existsSync(DATA_FILE)) {
    throw new Error(`App catalog not found: ${path.relative(ROOT, DATA_FILE)}. Restore it before regenerating detail pages.`);
  }
  const data = JSON.parse(fs.readFileSync(DATA_FILE, "utf8"));
  const subcategories = data?.[CATALOG_TYPE]?.subcategories;
  if (!subcategories || typeof subcategories !== "object" || Array.isArray(subcategories)) {
    throw new Error(`Expected data/${ITEMS_LABEL}.json to contain ${ITEMS_LABEL}.subcategories.`);
  }

  const outputPaths = new Set();
  const categories = Object.entries(subcategories).map(([key, category]) => {
    if (!category || !Array.isArray(category.apps)) {
      throw new Error(`Category "${key}" must contain an apps array.`);
    }
    const slug = category.slug || slugify(key);
    const name = category.name || CATEGORY_LABELS[slug] || slug.split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join(" ");
    const apps = category.apps.map((app) => {
      if (!app || typeof app !== "object") {
        throw new Error(`An item in category "${name}" must be an object.`);
      }
      const outputPath = getPagePath(app);
      if (outputPaths.has(outputPath.toLowerCase())) {
        throw new Error(`More than one app maps to ${outputPath}.`);
      }
      outputPaths.add(outputPath.toLowerCase());
      return {
        ...app,
        title: typeof app.title === "string" && app.title.trim() ? app.title.trim() : getTitleFromPath(outputPath, ROUTE_PREFIX),
        appurl: outputPath,
        categoryName: name,
        categorySlug: slug,
        pagePath: outputPath,
      };
    });
    return { name, slug, apps };
  });
  return categories;
}

function getIndexShell() {
  const index = fs.readFileSync(INDEX_FILE, "utf8");
  const headerStart = index.indexOf("<!-- header -->");
  const headerEnd = index.indexOf("<!-- Hero Section -->", headerStart);
  const footerStart = index.indexOf("<footer>", headerEnd);
  const footerEnd = index.indexOf("</footer>", footerStart);
  if (headerStart < 0 || headerEnd < 0 || footerStart < 0 || footerEnd < 0) {
    throw new Error("Could not extract the shared header and footer from index.html.");
  }
  const rootLinks = (markup) => markup
    .replace(/(href|action)="([^"]+)"/g, (_match, attribute, value) => `${attribute}="${publicPath(value)}"`);
  return {
    header: rootLinks(index.slice(headerStart, headerEnd)).trim(),
    footer: rootLinks(index.slice(footerStart, footerEnd + "</footer>".length)).trim(),
  };
}

function loadHomeCategories(type) {
  const labels = type === "apps" ? CATEGORY_LABELS : { action: "Action", racing: "Racing" };
  const filePath = path.join(ROOT, "data", `${type}.json`);
  const data = JSON.parse(fs.readFileSync(filePath, "utf8"));
  const subcategories = data?.[type]?.subcategories;
  if (!subcategories || typeof subcategories !== "object" || Array.isArray(subcategories)) {
    throw new Error(`Expected data/${type}.json to contain ${type}.subcategories.`);
  }
  const routePrefix = "/app/";
  return Object.entries(subcategories).map(([key, category]) => {
    if (!category || !Array.isArray(category.apps)) {
      throw new Error(`Category "${key}" in data/${type}.json must contain an apps array.`);
    }
    const slug = category.slug || slugify(key);
    const name = category.name || labels[slug] || slug.split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join(" ");
    const apps = category.apps.slice(0, 9).map((app) => {
      if (!app || typeof app !== "object") {
        throw new Error(`An item in category "${name}" must be an object.`);
      }
      const detailUrl = getDetailPath(app, routePrefix, type === "apps" ? "app" : "game");
      const title = typeof app.title === "string" && app.title.trim()
        ? app.title.trim()
        : getTitleFromPath(detailUrl, routePrefix);
      return { ...app, title, detailUrl };
    });
    return { name, slug, apps, type, catalogName: type === "apps" ? "Apps" : "Games" };
  });
}

function writeSearchIndex() {
  const catalog = ["apps", "games"].flatMap((type) => {
    const data = JSON.parse(fs.readFileSync(path.join(ROOT, "data", `${type}.json`), "utf8"));
    const subcategories = data?.[type]?.subcategories;
    if (!subcategories || typeof subcategories !== "object" || Array.isArray(subcategories)) {
      throw new Error(`Expected data/${type}.json to contain ${type}.subcategories.`);
    }
    const labels = type === "apps" ? CATEGORY_LABELS : { action: "Action", racing: "Racing" };
    return Object.entries(subcategories).flatMap(([key, category]) => {
      if (!category || !Array.isArray(category.apps)) {
        throw new Error(`Category "${key}" in data/${type}.json must contain an apps array.`);
      }
      const slug = category.slug || slugify(key);
      const categoryName = category.name || labels[slug] || slug.split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join(" ");
      return category.apps.map((item) => {
        if (!item || typeof item !== "object") {
          throw new Error(`An item in category "${categoryName}" must be an object.`);
        }
        const routePrefix = "/app/";
        const detailPath = getDetailPath(item, routePrefix, type === "apps" ? "app" : "game");
        const title = typeof item.title === "string" && item.title.trim()
          ? item.title.trim()
          : getTitleFromPath(detailPath, routePrefix);
        return {
          title,
          ratings: item.ratings,
          appurl: detailPath,
          icon: item.icon,
          categoryName,
          categorySlug: slug,
          developer: item.developer,
          description: [item.description1, item.description2]
            .filter(Boolean)
            .map((text) => contentToPlainText(renderContentHtml(text)))
            .join(" "),
          type,
        };
      });
    });
  });
  const json = JSON.stringify(catalog).replace(/</g, "\\u003c");
  fs.writeFileSync(SEARCH_INDEX_FILE, `window.catalogSearchItems = ${json};\n`, "utf8");
}

function updateAppsListingScript() {
  const appsScriptPath = path.join(ROOT, "scripts", "apps.js");
  const currentScript = fs.readFileSync(appsScriptPath, "utf8");
  const rendererStart = currentScript.indexOf("const categoryList = document.querySelector");
  if (rendererStart < 0) {
    throw new Error("Could not locate the app category renderer in apps.js.");
  }

  const categories = loadCategories().map((category) => ({
    name: category.name,
    slug: category.slug,
    apps: category.apps.map((app) => ({
      title: app.title,
      ratings: app.ratings,
      appurl: app.appurl,
      icon: app.icon ? assetUrl(safeLocalPath(app.icon, `${app.title} icon`)) : app.icon,
    })),
  }));
  const dataScript = `const appCategories = ${JSON.stringify(categories, null, 2)};\n\n`;
  const renderer = currentScript.slice(rendererStart);
  fs.writeFileSync(appsScriptPath, `${dataScript}${renderer}`, "utf8");
}

