function writePages(categories, shell) {
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  const allApps = categories.flatMap((category) => category.apps);
  const expectedFiles = new Set();
  let written = 0;

  for (const category of categories) {
    for (const app of category.apps) {
      const outputPath = path.join(ROOT, app.pagePath.replace(/^\/+/, ""));
      expectedFiles.add(path.resolve(outputPath).toLowerCase());
      if (fs.existsSync(outputPath) && !fs.readFileSync(outputPath, "utf8").includes(GENERATED_MARKER)) {
        throw new Error(`Refusing to overwrite an unmanaged file: ${path.relative(ROOT, outputPath)}`);
      }
      const html = `${GENERATED_MARKER}\n${renderPage(app, category, allApps, shell)}\n`;
      fs.mkdirSync(path.dirname(outputPath), { recursive: true });
      fs.writeFileSync(outputPath, html, "utf8");
      written += 1;
    }
  }

  for (const entry of fs.readdirSync(OUTPUT_DIR, { withFileTypes: true })) {
    if (!entry.isFile() || !entry.name.toLowerCase().endsWith(".html")) {
      continue;
    }
    const fullPath = path.join(OUTPUT_DIR, entry.name);
    const normalizedPath = path.resolve(fullPath).toLowerCase();
    if (!expectedFiles.has(normalizedPath) && fs.readFileSync(fullPath, "utf8").includes(GENERATED_MARKER)) {
      fs.unlinkSync(fullPath);
    }
  }
  writeSitemap(allApps);
  return written;
}

function writeSitemap(apps) {
  if (fs.existsSync(SITEMAP_FILE) && !fs.readFileSync(SITEMAP_FILE, "utf8").includes(GENERATED_SITEMAP_MARKER)) {
    throw new Error("Refusing to overwrite the existing unmanaged app-sitemap.xml file.");
  }
  const urls = apps.map((app) => `  <url><loc>${escapeHtml(absoluteUrl(app.pagePath))}</loc></url>`).join("\n");
  const sitemap = `<?xml version="1.0" encoding="UTF-8"?>\n${GENERATED_SITEMAP_MARKER}\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`;
  fs.writeFileSync(SITEMAP_FILE, sitemap, "utf8");
}

try {
  const categories = loadCategories();
  const shell = getIndexShell();
  const totalApps = categories.reduce((count, category) => count + category.apps.length, 0);
  updateHomePage();
  updatePolicyAdSlots();
  const written = writePages(categories, shell);
  console.log(`Generated ${written} ${ITEM_LABEL} detail pages for ${totalApps} ${ITEMS_LABEL} across ${categories.length} categories in ${path.relative(ROOT, OUTPUT_DIR)}.`);
  console.log(`Canonical domain: ${SITE_URL}`);
  console.log("To use a different public domain, set SITE_URL before running this script.");
} catch (error) {
  console.error(`${ITEM_LABEL[0].toUpperCase()}${ITEM_LABEL.slice(1)} page generation failed: ${error.message}`);
  process.exitCode = 1;
}
