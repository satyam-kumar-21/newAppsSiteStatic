const fs = require("node:fs");
const path = require("node:path");

const ROOT = __dirname;
const INDEX_FILE = path.join(ROOT, "index.html");
const SITE_URL = (process.env.SITE_URL || "https://brandname.com").replace(/\/+$/, "");
const CATALOG_TYPE = process.argv[2] || "apps";
const IS_GAME = CATALOG_TYPE === "games";
if (!["apps", "games"].includes(CATALOG_TYPE)) {
  throw new Error('Choose a catalog type: "apps" or "games".');
}
const ITEM_LABEL = IS_GAME ? "game" : "app";
const ITEMS_LABEL = IS_GAME ? "games" : "apps";
const CATALOG_NAME = IS_GAME ? "Games" : "Apps";
const ROUTE_PREFIX = IS_GAME ? "/game/" : "/app/";
const DATA_FILE = path.join(ROOT, "data", `${ITEMS_LABEL}.json`);
const OUTPUT_DIR = path.join(ROOT, IS_GAME ? "game" : "app");
const SITEMAP_FILE = path.join(ROOT, `${ITEM_LABEL}-sitemap.xml`);
const GENERATED_MARKER = IS_GAME
  ? "<!-- Generated by generate-app-pages.js for games. Do not edit this file directly. -->"
  : "<!-- Generated by generate-app-pages.js. Do not edit this file directly. -->";
const GENERATED_SITEMAP_MARKER = "<!-- Generated by generate-app-pages.js. -->";
const HOME_SECTION_START = "<!-- Generated app and game category previews start. -->";
const HOME_SECTION_END = "<!-- Generated app and game category previews end. -->";
const CATEGORY_LABELS = {
  "photo-video": "Photo & Video",
  "music-audio": "Music & Audio",
};

function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>"']/g, (character) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;",
  })[character]);
}

function renderAdSlot(slotId, generatedAttribute = "") {
  const safeId = slotId.toLowerCase().replace(/[^a-z0-9-]+/g, "-").replace(/^-+|-+$/g, "");
  return `<aside class="ad-slot" id="ad-slot-${safeId}" aria-label="Advertisement"${generatedAttribute}><div><span class="ad-slot-label">Advertisement</span><span class="ad-slot-copy">Ad placement reserved</span></div></aside>`;
}

function safeLocalPath(value, fieldName) {
  if (typeof value !== "string" || !value.startsWith("/") || value.startsWith("//") || value.includes("\\") || value.split("/").includes("..")) {
    throw new Error(`Invalid ${fieldName} path: ${value}`);
  }
  return value;
}

function getPagePath(app) {
  const appUrl = safeLocalPath(app.appurl, `${app.title} appurl`).replace(/\/+$/, "");
  if (!appUrl.startsWith(ROUTE_PREFIX) || appUrl.length <= ROUTE_PREFIX.length) {
    throw new Error(`Expected a ${ITEM_LABEL} URL under ${ROUTE_PREFIX}: ${app.appurl}`);
  }
  return `${appUrl}.html`;
}

function absoluteUrl(localPath) {
  return new URL(safeLocalPath(localPath, "URL"), `${SITE_URL}/`).href;
}

function safeExternalUrl(value) {
  if (typeof value !== "string" || !value.trim()) {
    return "";
  }
  const url = new URL(value);
  if (url.protocol !== "https:" && url.protocol !== "http:") {
    throw new Error(`Unsupported store URL protocol: ${value}`);
  }
  return url.href;
}

function loadCategories() {
  if (!fs.existsSync(DATA_FILE)) {
    throw new Error(`App catalog not found: ${path.relative(ROOT, DATA_FILE)}. Restore it before regenerating detail pages.`);
  }
  const data = JSON.parse(fs.readFileSync(DATA_FILE, "utf8"));
  const subcategories = data?.[CATALOG_TYPE]?.subcategories;
  if (!subcategories || typeof subcategories !== "object" || Array.isArray(subcategories)) {
    throw new Error(`Expected data/${ITEMS_LABEL}.json to contain ${ITEMS_LABEL}.subcategories.`);
  }

  const outputPaths = new Set();
  const categories = Object.entries(subcategories).map(([key, category]) => {
    if (!category || !Array.isArray(category.apps)) {
      throw new Error(`Category "${key}" must contain an apps array.`);
    }
    const slug = category.slug || key;
    const name = category.name || CATEGORY_LABELS[slug] || slug.split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join(" ");
    const apps = category.apps.map((app) => {
      if (!app || !app.title || !app.appurl) {
        throw new Error(`An app in category "${name}" is missing its title or appurl.`);
      }
      const outputPath = getPagePath(app);
      if (outputPaths.has(outputPath.toLowerCase())) {
        throw new Error(`More than one app maps to ${outputPath}.`);
      }
      outputPaths.add(outputPath.toLowerCase());
      return { ...app, categoryName: name, categorySlug: slug, pagePath: outputPath };
    });
    return { name, slug, apps };
  });
  return categories;
}

function getIndexShell() {
  const index = fs.readFileSync(INDEX_FILE, "utf8");
  const headerStart = index.indexOf("<!-- header -->");
  const headerEnd = index.indexOf("<!-- Hero Section -->", headerStart);
  const footerStart = index.indexOf("<footer>", headerEnd);
  const footerEnd = index.indexOf("</footer>", footerStart);
  if (headerStart < 0 || headerEnd < 0 || footerStart < 0 || footerEnd < 0) {
    throw new Error("Could not extract the shared header and footer from index.html.");
  }
  const rootLinks = (markup) => markup.replace(/href="(about|privacy|terms|disclaimer|index)\.html"/g, 'href="/$1.html"');
  return {
    header: rootLinks(index.slice(headerStart, headerEnd)).trim(),
    footer: rootLinks(index.slice(footerStart, footerEnd + "</footer>".length)).trim(),
  };
}

function loadHomeCategories(type) {
  const labels = type === "apps" ? CATEGORY_LABELS : { action: "Action", racing: "Racing" };
  const filePath = path.join(ROOT, "data", `${type}.json`);
  const data = JSON.parse(fs.readFileSync(filePath, "utf8"));
  const subcategories = data?.[type]?.subcategories;
  if (!subcategories || typeof subcategories !== "object" || Array.isArray(subcategories)) {
    throw new Error(`Expected data/${type}.json to contain ${type}.subcategories.`);
  }
  const routePrefix = type === "apps" ? "/app/" : "/game/";
  return Object.entries(subcategories).map(([key, category]) => {
    if (!category || !Array.isArray(category.apps)) {
      throw new Error(`Category "${key}" in data/${type}.json must contain an apps array.`);
    }
    const slug = category.slug || key;
    const name = category.name || labels[slug] || slug.split("-").map((part) => part[0].toUpperCase() + part.slice(1)).join(" ");
    const apps = category.apps.slice(0, 9).map((app) => {
      if (!app?.title || !app.appurl) {
        throw new Error(`An item in category "${name}" is missing its title or appurl.`);
      }
      const url = safeLocalPath(app.appurl, `${app.title} URL`).replace(/\/+$/, "");
      if (!url.startsWith(routePrefix) || url.length <= routePrefix.length) {
        throw new Error(`Expected ${app.title} to have a URL under ${routePrefix}.`);
      }
      return { ...app, detailUrl: `${url}.html` };
    });
    return { name, slug, apps, type, catalogName: type === "apps" ? "Apps" : "Games" };
  });
}

function renderHomeCategory(category) {
  const categoryUrl = `/${category.type}.html?category=${encodeURIComponent(category.slug)}#category-${encodeURIComponent(category.slug)}`;
  const cards = category.apps.map((app) => {
    const iconContent = app.icon
      ? `<img src="${escapeHtml(safeLocalPath(app.icon, `${app.title} icon`))}" alt="" loading="lazy" width="56" height="56" />`
      : `<span aria-hidden="true">${escapeHtml(app.title.split(/\s+/).slice(0, 2).map((word) => word.charAt(0)).join("").toUpperCase())}</span>`;
    const rating = Number.isFinite(Number(app.ratings))
      ? `<span class="app-card-rating"><span class="app-card-star" aria-hidden="true">★</span>${escapeHtml(Number(app.ratings).toFixed(1))}</span>`
      : "";
    return `<a class="app-card" href="${escapeHtml(app.detailUrl)}" aria-label="${escapeHtml(`${app.title}, ${category.name}, rated ${app.ratings} out of 5`)}"><span class="app-card-icon" aria-hidden="true">${iconContent}</span><span class="app-card-copy"><span class="app-card-title">${escapeHtml(app.title)}</span><span class="app-card-category">${escapeHtml(category.name)}</span>${rating}</span></a>`;
  }).join("\n");
  return `<section class="apps-category" id="home-${category.type}-${escapeHtml(category.slug)}" aria-labelledby="home-heading-${category.type}-${escapeHtml(category.slug)}">
  <div class="apps-category-heading">
    <h3 id="home-heading-${category.type}-${escapeHtml(category.slug)}">${escapeHtml(category.name)}</h3>
    <a class="apps-view-all" href="${escapeHtml(categoryUrl)}" aria-label="View all ${escapeHtml(category.name)} ${category.type}" title="View all ${escapeHtml(category.name)} ${category.type}">
      <svg viewBox="0 0 24 24" aria-hidden="true"><path d="M5 12h13m-6-6 6 6-6 6" /></svg>
    </a>
  </div>
  <div class="apps-grid" role="list">${cards.replaceAll('<a class="app-card"', '<a class="app-card" role="listitem"')}</div>
</section>
${renderAdSlot(`home-${category.type}-${category.slug}`)}`;
}

function updateHomePage() {
  const index = fs.readFileSync(INDEX_FILE, "utf8");
  const startIndex = index.indexOf(HOME_SECTION_START);
  const endIndex = index.indexOf(HOME_SECTION_END);
  if ((startIndex >= 0) !== (endIndex >= 0) || (startIndex >= 0 && endIndex < startIndex)) {
    throw new Error("Homepage category preview markers are incomplete or out of order.");
  }

  const apps = loadHomeCategories("apps");
  const games = loadHomeCategories("games");
  const appSections = apps.map(renderHomeCategory).join("\n");
  const gameSections = games.map(renderHomeCategory).join("\n");
  const markup = `${HOME_SECTION_START}
<section class="apps-page home-catalog" aria-labelledby="home-apps-title">
  <header class="home-catalog-heading">
    <p class="apps-eyebrow">Explore the catalog</p>
    <h2 id="home-apps-title">Popular app categories</h2>
    <p>Discover popular apps, browse by category, and find the right tools for your day.</p>
  </header>
  <div class="apps-category-list">${appSections}</div>
  <p class="home-catalog-link"><a href="/apps.html">Browse all apps</a></p>
</section>
<section class="apps-page home-catalog" aria-labelledby="home-games-title">
  <header class="home-catalog-heading">
    <p class="apps-eyebrow">Play something new</p>
    <h2 id="home-games-title">Popular game categories</h2>
    <p>Explore top-rated games across the categories available in our catalog.</p>
  </header>
  <div class="apps-category-list">${gameSections}</div>
  <p class="home-catalog-link"><a href="/games.html">Browse all games</a></p>
</section>
${HOME_SECTION_END}`;

  let updatedIndex;
  if (startIndex >= 0) {
    const endAfterMarker = endIndex + HOME_SECTION_END.length;
    updatedIndex = `${index.slice(0, startIndex)}${markup}${index.slice(endAfterMarker)}`;
  } else {
    const heroEnd = index.indexOf("</section>", index.indexOf('<section class="home-hero"'));
    if (heroEnd < 0) {
      throw new Error("Could not locate the homepage hero section in index.html.");
    }
    const insertAt = heroEnd + "</section>".length;
    updatedIndex = `${index.slice(0, insertAt)}\n\n${markup}${index.slice(insertAt)}`;
  }

  if (!/<link rel="stylesheet" href="apps\.css"\s*\/>/.test(updatedIndex)) {
    updatedIndex = updatedIndex.replace(
      /(<link rel="stylesheet" href="responsive\.css"\s*\/>)/,
      '$1\n    <link rel="stylesheet" href="apps.css" />',
    );
  }
  fs.writeFileSync(INDEX_FILE, updatedIndex, "utf8");
  console.log(`Updated index.html with ${apps.length} app categories and ${games.length} game categories.`);
}

function updatePolicyAdSlots() {
  const policyPages = ["privacy.html", "terms.html", "disclaimer.html"];
  const managedSlotPattern = /<aside class="ad-slot"[^>]*data-generated-ad-slot="policy">[\s\S]*?<\/aside>/g;
  const policySectionPattern = /<section class="(?:about-hero legal-hero|legal-section)"[^>]*>[\s\S]*?<\/section>/g;

  for (const pageName of policyPages) {
    const filePath = path.join(ROOT, pageName);
    const original = fs.readFileSync(filePath, "utf8");
    const cleanPage = original.replace(managedSlotPattern, "");
    let sectionIndex = 0;
    let updated = cleanPage.replace(policySectionPattern, (section) => {
      sectionIndex += 1;
      return `${section}\n${renderAdSlot(`policy-${path.basename(pageName, ".html")}-${sectionIndex}`, ' data-generated-ad-slot="policy"')}`;
    });
    if (sectionIndex === 0) {
      throw new Error(`Could not find policy content sections in ${pageName}.`);
    }
    if (!/<link rel="stylesheet" href="apps\.css"\s*\/>/.test(updated)) {
      updated = updated.replace(
        /(<link rel="stylesheet" href="responsive\.css"\s*\/>)/,
        '$1\n    <link rel="stylesheet" href="apps.css" />',
      );
    }
    fs.writeFileSync(filePath, updated, "utf8");
  }
}

function renderAppCard(app) {
  const icon = app.icon
    ? `<img class="app-detail-card-icon" src="${escapeHtml(safeLocalPath(app.icon, `${app.title} icon`))}" alt="" loading="lazy" width="56" height="56" />`
    : `<span class="app-detail-card-fallback" aria-hidden="true">${escapeHtml(app.title.slice(0, 2).toUpperCase())}</span>`;
  const rating = Number.isFinite(Number(app.ratings)) ? `<span class="app-detail-card-rating"><span aria-hidden="true">★</span> ${escapeHtml(Number(app.ratings).toFixed(1))}</span>` : "";
  return `<a class="app-detail-card" href="${escapeHtml(app.pagePath)}">${icon}<span class="app-detail-card-copy"><span class="app-detail-card-title">${escapeHtml(app.title)}</span><span class="app-detail-card-category">${escapeHtml(app.categoryName)}</span>${rating}</span></a>`;
}

function renderMetadata(app) {
  const rows = [
    ["Category", app.categoryName],
    ["Latest version", app["latest-version"]],
    ["Published", app["publish-date"]],
    ["Developer", app.developer],
    ["Security", app.security],
    ["Price", app.price],
    ["Downloads", app.downloads],
    ["Ratings", app.ratings ? `${app.ratings} out of 5` : ""],
  ].filter(([, value]) => value !== undefined && value !== null && String(value).trim());
  return rows.map(([label, value]) => `<div class="app-detail-meta-row"><dt>${escapeHtml(label)}</dt><dd>${escapeHtml(value)}</dd></div>`).join("\n");
}

function renderScreenshots(app) {
  if (!Array.isArray(app.screenshots) || app.screenshots.length === 0) {
    return "";
  }
  const screenshots = app.screenshots.map((screenshot, index) => {
    const imagePath = safeLocalPath(screenshot, `${app.title} screenshot`);
    return `<figure><img src="${escapeHtml(imagePath)}" alt="${escapeHtml(`${app.title} ${ITEM_LABEL} screenshot ${index + 1}`)}" loading="lazy" decoding="async" /></figure>`;
  }).join("\n");
  return `<section class="app-detail-section" aria-labelledby="app-screenshots-title"><h2 id="app-screenshots-title">${escapeHtml(app.title)} screenshots</h2><div class="app-detail-screenshots">${screenshots}</div></section>`;
}

function renderStoreLinks(app) {
  const playStore = safeExternalUrl(app["playstore-url"]);
  const appStore = safeExternalUrl(app["appstore-url"]);
  if (!playStore && !appStore) {
    return "";
  }
  const links = [
    playStore && `<a class="app-detail-store-link" href="${escapeHtml(playStore)}" target="_blank" rel="noopener noreferrer">Get it on Google Play</a>`,
    appStore && `<a class="app-detail-store-link app-detail-store-link-secondary" href="${escapeHtml(appStore)}" target="_blank" rel="noopener noreferrer">Download on the App Store</a>`,
  ].filter(Boolean).join("\n");
  return `<section class="app-detail-section" aria-labelledby="app-download-title"><h2 id="app-download-title">Download ${escapeHtml(app.title)}</h2><div class="app-detail-store-links">${links}</div></section>`;
}

function renderSchema(app, relatedApps, description) {
  const appSchema = {
    "@context": "https://schema.org",
    "@type": IS_GAME ? "VideoGame" : "SoftwareApplication",
    "name": app.title,
    "url": absoluteUrl(app.pagePath),
    "description": description,
    "applicationCategory": app.categoryName,
    "operatingSystem": IS_GAME ? undefined : "Android, iOS",
    "image": app.icon ? absoluteUrl(app.icon) : undefined,
    "softwareVersion": app["latest-version"] || undefined,
    "datePublished": app["publish-date"] || undefined,
    "author": app.developer ? { "@type": "Organization", "name": app.developer } : undefined,
    "aggregateRating": Number.isFinite(Number(app.ratings)) && Number(app["ratings-counts"]) > 0 ? {
      "@type": "AggregateRating",
      "ratingValue": Number(app.ratings),
      "ratingCount": Number(app["ratings-counts"]),
      "bestRating": 5,
      "worstRating": 1,
    } : undefined,
    "offers": app.price?.toLowerCase() === "free" ? { "@type": "Offer", "price": "0", "priceCurrency": "USD" } : undefined,
  };
  const itemListSchema = {
    "@context": "https://schema.org",
    "@type": "ItemList",
    "name": `Similar ${app.categoryName} ${ITEMS_LABEL}`,
    "itemListElement": relatedApps.map((related, index) => ({
      "@type": "ListItem",
      "position": index + 1,
      "name": related.title,
      "url": absoluteUrl(related.pagePath),
    })),
  };
  const breadcrumbSchema = {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    "itemListElement": [
      { "@type": "ListItem", "position": 1, "name": "Home", "item": `${SITE_URL}/` },
      { "@type": "ListItem", "position": 2, "name": CATALOG_NAME, "item": `${SITE_URL}/${ITEMS_LABEL}.html` },
      { "@type": "ListItem", "position": 3, "name": app.categoryName, "item": `${SITE_URL}/${ITEMS_LABEL}.html#category-${encodeURIComponent(app.categorySlug)}` },
      { "@type": "ListItem", "position": 4, "name": app.title, "item": absoluteUrl(app.pagePath) },
    ],
  };
  return [appSchema, itemListSchema, breadcrumbSchema]
    .map((schema) => `<script type="application/ld+json">${JSON.stringify(schema, (_key, value) => value === undefined ? undefined : value).replace(/</g, "\\u003c")}</script>`)
    .join("\n");
}

