const categoryList = document.querySelector("#games-category-list");
const pageTitle = document.querySelector("#games-page-title");
const pageDescription = document.querySelector("#games-page-description");
const metaDescription = document.querySelector('meta[name="description"]');

if (categoryList && pageTitle && pageDescription) {
  const requestedSlug = new URLSearchParams(window.location.search).get("category");
  const selectedCategory = appCategories.find((category) => category.slug === requestedSlug);
  const categoriesToShow = selectedCategory ? [selectedCategory] : appCategories;
  const appPageUrl = new URL("games.html", window.location.href);

  function getAppPageUrl(app) {
    return `${app.appurl.replace(/\/+$/, "")}.html`;
  }

  function createAdSlot(slotId) {
    const slot = document.createElement("aside");
    slot.className = "ad-slot";
    slot.id = `ad-slot-${slotId}`;
    slot.setAttribute("aria-label", "Advertisement");

    const content = document.createElement("div");
    const label = document.createElement("span");
    label.className = "ad-slot-label";
    label.textContent = "Advertisement";

    const copy = document.createElement("span");
    copy.className = "ad-slot-copy";
    copy.textContent = "Ad placement reserved";
    content.append(label, copy);
    slot.append(content);
    return slot;
  }

  function createAppCard(app, category) {
    const card = document.createElement("a");
    card.className = "app-card";
    card.href = getAppPageUrl(app);
    card.setAttribute("aria-label", `${app.title}, ${category.name}, rated ${app.ratings} out of 5`);

    const icon = document.createElement("span");
    icon.className = "app-card-icon";
    icon.setAttribute("aria-hidden", "true");
    const initials = document.createElement("span");
    initials.textContent = app.title
      .split(/\s+/)
      .slice(0, 2)
      .map((word) => word.charAt(0))
      .join("")
      .toUpperCase();
    icon.append(initials);

    if (app.icon) {
      const image = document.createElement("img");
      image.src = app.icon;
      image.alt = "";
      image.loading = "lazy";
      image.decoding = "async";
      image.addEventListener("error", () => image.remove());
      icon.append(image);
    }

    const copy = document.createElement("span");
    copy.className = "app-card-copy";

    const title = document.createElement("span");
    title.className = "app-card-title";
    title.textContent = app.title;

    const categoryName = document.createElement("span");
    categoryName.className = "app-card-category";
    categoryName.textContent = category.name;

    const rating = document.createElement("span");
    rating.className = "app-card-rating";
    rating.setAttribute("aria-label", `Rated ${app.ratings} out of 5`);

    const star = document.createElement("span");
    star.className = "app-card-star";
    star.setAttribute("aria-hidden", "true");
    star.textContent = "★";

    const ratingValue = document.createElement("span");
    ratingValue.textContent = app.ratings.toFixed(1);

    rating.append(star, ratingValue);
    copy.append(title, categoryName, rating);
    card.append(icon, copy);
    return card;
  }

  function createCategorySection(category, showAll) {
    const section = document.createElement("section");
    section.className = "apps-category";
    section.id = `category-${category.slug}`;
    section.setAttribute("aria-labelledby", `heading-${category.slug}`);

    const heading = document.createElement("div");
    heading.className = "apps-category-heading";

    const title = document.createElement("h2");
    title.id = `heading-${category.slug}`;
    title.textContent = category.name;

    heading.append(title);
    if (!showAll) {
      const viewAll = document.createElement("a");
      viewAll.className = "apps-view-all";
      viewAll.href = `games.html?category=${encodeURIComponent(category.slug)}#category-${encodeURIComponent(category.slug)}`;
      viewAll.setAttribute("aria-label", `View all ${category.name} games`);
      viewAll.title = `View all ${category.name} games`;

      const arrow = document.createElementNS("http://www.w3.org/2000/svg", "svg");
      arrow.setAttribute("viewBox", "0 0 24 24");
      arrow.setAttribute("aria-hidden", "true");

      const arrowPath = document.createElementNS("http://www.w3.org/2000/svg", "path");
      arrowPath.setAttribute("d", "M5 12h13m-6-6 6 6-6 6");
      arrow.append(arrowPath);
      viewAll.append(arrow);
      heading.append(viewAll);
    }

    const grid = document.createElement("div");
    grid.className = "apps-grid";
    grid.setAttribute("role", "list");

    const appsToShow = showAll ? category.apps : category.apps.slice(0, 9);
    appsToShow.forEach((app) => {
      const card = createAppCard(app, category);
      card.setAttribute("role", "listitem");
      grid.append(card);
    });

    section.append(heading, grid);
    return section;
  }

  function setStructuredData(categories) {
    const existing = document.querySelector("#apps-structured-data");
    existing?.remove();

    const structuredData = {
      "@context": "https://schema.org",
      "@type": "ItemList",
      "itemListElement": categories.flatMap((category) =>
        category.apps.map((app, index) => ({
          "@type": "ListItem",
          "position": index + 1,
          "name": app.title,
          "url": new URL(getAppPageUrl(app), window.location.origin).href,
          "category": category.name,
        })),
      ),
    };

    const script = document.createElement("script");
    script.id = "apps-structured-data";
    script.type = "application/ld+json";
    script.textContent = JSON.stringify(structuredData).replace(/</g, "\\u003c");
    document.head.append(script);
  }

  if (requestedSlug && !selectedCategory) {
    pageTitle.textContent = "App category not found";
    pageDescription.textContent = "The requested game category is unavailable. Browse all game categories below.";
    document.title = "Game Category Not Found | BRANDNAME";
    if (metaDescription) {
      metaDescription.content = pageDescription.textContent;
    }
    appCategories.forEach((category) => {
      categoryList.append(createCategorySection(category, false), createAdSlot(`games-${category.slug}`));
    });
  } else if (selectedCategory) {
    pageTitle.textContent = `All ${selectedCategory.name} games`;
    pageDescription.textContent = `Browse every ${selectedCategory.name.toLowerCase()} game in our catalog, with ratings and links to each game.`;
    document.title = `All ${selectedCategory.name} Games | BRANDNAME`;
    if (metaDescription) {
      metaDescription.content = pageDescription.textContent;
    }

    const backLink = document.createElement("a");
    backLink.className = "apps-back-link";
    backLink.href = appPageUrl.href;
    backLink.textContent = "Browse all categories";
    categoryList.append(
      backLink,
      createCategorySection(selectedCategory, true),
      createAdSlot(`games-${selectedCategory.slug}`),
    );
  } else {
    appCategories.forEach((category) => {
      categoryList.append(createCategorySection(category, false), createAdSlot(`games-${category.slug}`));
    });
    if (metaDescription) {
      metaDescription.content = pageDescription.textContent.trim();
    }
  }

  setStructuredData(categoriesToShow);
}
